/// 呼ばれる回数の上限の方針（★**N-26** の (1) の★★既定値★★）。
///
/// ★**この型そのものは決定ではない。★★軸である★★。**
class RateLimitPolicy {
  /// 窓のあいだに通す回数を決める（★★限-2★★）。
  const RateLimitPolicy.perWindow({
    required this.maxRequests,
    required this.window,
  })  : refuses = true,
        assert(
          maxRequests > 0,
          '★0 以下は「断らない」ではなく「全部断る」になる',
        );

  /// 断らない（★★限-1★★）。
  ///
  /// ★★**「上限を置かない」も★この型の 1 つの値である**★★（★上の doc）。
  const RateLimitPolicy.unlimited()
      : maxRequests = 0,
        window = Duration.zero,
        refuses = false;

  /// 窓のあいだに通す回数。★★[refuses] が `false` なら読まれない★★。
  ///
  /// ★★ 0 を「断らない」の印にしない ★★
  /// ★**0 は「★★全部断る★★」であり、★★意味が正反対である★★。**
  /// → ★**「断るかどうか」は★[refuses] が★別に持つ**。
  /// ★[RateLimitPolicy.perWindow] は★0 以下を `assert` で止める（★**対で固定する**）。
  final int maxRequests;

  /// 数える窓の長さ。
  final Duration window;

  /// 断る方針か。★`false` なら [maxRequests] も [window] も読まれない。
  final bool refuses;

  /// 断らない方針か。
  bool get isUnlimited => !refuses;
}

