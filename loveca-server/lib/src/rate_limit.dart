/// 相手ごとに、窓のあいだに通した回数を数える。
///
/// ★★ 覚えるのは★窓のあいだに来た分だけである ★★
/// ★**[allow] を呼ぶたびに★★窓より古い記録を★全部の相手について捨てる★★**。
/// → ★**覚えている量は「★窓のあいだに来た（住所 × 通った回数）」で頭打ちになる。**
///
/// ★★ 最初は★引かれた相手だけを掃除していた。★★対が偽だと教えた★★ ★★
/// ★**引かれた相手だけを掃除する形では、★★二度と来ない相手が永久に残る★★。**
/// ★**doc にはそのとき既に「頭打ちになる」と書いてあった** —— ★★偽だった★★。
/// → ★**「空になった相手は忘れる」の対が★落ちて分かった**（★書く前ではなく★★走らせて分かった★★）。
/// ★★**型は D-15 (j) の (j-甲) である。★出す前に (j-乙) が働いた。**★★
///
/// ★★ 掃除の費用（★測っていない / **D-28**）★★
/// ★**1 回の [allow] が★★覚えている相手の数に比例する★★。**
/// ★**「軽い」とも「重い」とも書かない** —— ★★測っていない★★。
/// ★**上限が無いのは変わらない**（★住所を無数に変えられる相手には効かない）。
class RateLimiter {
  RateLimiter(this.policy, {DateTime Function()? clock})
      : _clock = clock ?? DateTime.now;

  final RateLimitPolicy policy;
  final DateTime Function() _clock;

  /// 相手 → 通した時刻の列（★★古い順★★）。
  final Map<String, List<DateTime>> _accepted = <String, List<DateTime>>{};

  /// 通してよいか。★★通すときだけ数える★★（★上の doc）。
  bool allow(String key) {
    if (policy.isUnlimited) return true;
    final max = policy.maxRequests;

    final now = _clock();
    final cutoff = now.subtract(policy.window);

    // ★★ 全部の相手を掃除する（★引かれた相手だけでは足りない）★★
    //   ★**二度と来ない相手を★引かれた相手だけの掃除では★永久に忘れられない。**
    //   ★★対（「空になった相手は忘れる」）が★これを教えた★★（★上の doc）。
    _accepted.removeWhere((_, hits) {
      hits.removeWhere((t) => !t.isAfter(cutoff));
      return hits.isEmpty;
    });

    final current = _accepted[key];
    if (current != null && current.length >= max) return false;

    (_accepted[key] ??= <DateTime>[]).add(now);
    return true;
  }

  /// いま覚えている相手の数（★試験と診断のため）。
  int get trackedKeys => _accepted.length;
}

