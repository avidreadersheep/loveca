/// 枠 —— ★★どの口を★どの枠で数えるか（**N-27** の 論点 (2) の★★既定値★★）★★。
///
/// ★★ これは★決定ではない。★軸である ★★
/// ★**枠-1（すべて 1 つの枠）が答えなら、★★同じ値を 2 つ渡すだけで戻る★★**
/// （★[RateLimitPolicySet.uniform]）。★**分岐を消す必要が無い**（**D114-7** の理由 2）。
enum RateLimitFrame {
  /// ★人が押す口（`/auth` ／ `/accounts`）。★★知らないパスもここに入る★★。
  ///
  /// ★**知らないパスを同期の枠に入れない** —— ★★同期の枠は「1 回の同期が通ること」で寸法が決まっており、
  /// ★知らないパスはその勘定に入らない★★。
  human,

  /// ★プログラムが回す同期の口（`/decks` ／ `/decks/fetch` ／ `/decks/list`）。
  deckSync,
}

/// 枠ごとの方針。
class RateLimitPolicySet {
  const RateLimitPolicySet({required this.human, required this.deckSync});

  /// ★どの枠も同じ方針にする（★★枠-1 に戻す形★★）。
  const RateLimitPolicySet.uniform(RateLimitPolicy policy)
      : human = policy,
        deckSync = policy;

  /// ★どの枠も断らない（★★限-1 / ★試験で使う★★）。
  const RateLimitPolicySet.unlimited()
      : human = const RateLimitPolicy.unlimited(),
        deckSync = const RateLimitPolicy.unlimited();

  /// 人が押す枠の方針。
  final RateLimitPolicy human;

  /// 同期の枠の方針。
  final RateLimitPolicy deckSync;

  /// [frame] の方針。
  RateLimitPolicy of(RateLimitFrame frame) => switch (frame) {
        RateLimitFrame.human => human,
        RateLimitFrame.deckSync => deckSync,
      };
}

/// 既定の枠ごとの方針（★★これが「自分で決めた既定値」である★★）。
const RateLimitPolicySet defaultRateLimits = RateLimitPolicySet(
  human: defaultRateLimit,
  deckSync: defaultSyncRateLimit,
);

/// 枠ごとに数える（★★枠が違えば★別の勘定である★★）。
///
/// ★★ 枠ごとに [RateLimiter] を 1 つ持つ ★★
/// ★**鍵を混ぜて 1 つの表に入れない** —— ★★混ぜると★窓の掃除が★枠をまたいで効く★★。
/// ★**[RateLimiter] は 1 つの方針しか持たないので、★枠の数だけ要る。**
class ApiRateLimiter {
  ApiRateLimiter(this.policies, {DateTime Function()? clock})
      : _limiters = <RateLimitFrame, RateLimiter>{
          for (final frame in RateLimitFrame.values)
            frame: RateLimiter(policies.of(frame), clock: clock),
        };

  /// 枠ごとの方針。
  final RateLimitPolicySet policies;

  final Map<RateLimitFrame, RateLimiter> _limiters;

  /// [frame] の枠で [key] を通してよいか。
  bool allow(RateLimitFrame frame, String key) =>
      _limiters[frame]!.allow(key);

  /// [frame] の枠がいま覚えている相手の数（★試験と診断のため）。
  int trackedKeys(RateLimitFrame frame) => _limiters[frame]!.trackedKeys;
}
