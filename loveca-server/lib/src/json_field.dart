/// JSON の本体を読むときの共通の道具（決定 **D130-12**）。
///
/// ★★ なぜ切り出すか ★★
/// ★**「鍵が無い」と「型が違う」と「空文字」は★★別のことである★★。**
/// ★**1 か所で決めておかないと、★口が増えるたびに★違う扱いになる**
/// （★先例は `loveca_core` の `MasterData` のパース —— ★**未知キーで例外を投げる厳しさを 1 か所に置いている**）。
///
/// ★★ 「無い」と「空」を分ける ★★
/// | 何 | 扱い | ★なぜ |
/// |---|---|---|
/// | ★**鍵が無い / 型が違う** | ★★**投げる**★★ | ★**壊れた要求である**（★送り手の作りが違う） |
/// | ★**空文字** | ★★**通す**★★ | ★**間違った資格情報である**（★呼び出し側が判定する）。★★日常であって異常ではない★★ |
///
/// ★★ 混ぜると何が起きるか ★★
/// ★空文字を投げる側に寄せると、★**空のパスワードを送っただけで★★壊れた要求として扱われる★★。**
/// ★鍵の欠落を通す側に寄せると、★**フィールド名を間違えた実装が★★「パスワードが違う」として静かに落ちる★★。**
library;

/// [json] の [key] を文字列として読む。
///
/// ★**鍵が無い / 文字列でないときは [FormatException] を投げる。**
/// ★**空文字はそのまま返す**（★上の表）。
String requireJsonString(Map<String, Object?> json, String key) {
  if (!json.containsKey(key)) {
    throw FormatException('★鍵が無い: $key');
  }
  final value = json[key];
  if (value is! String) {
    throw FormatException('★文字列ではない: $key');
  }
  return value;
}
