/// 画像の保存先.
///
/// ★★ どこに置くかはここで決めない (門 キ / **N-1**) ★★
/// `docs/同期設計メモ.md` §32-6 の 8「画像の置き場と供給経路を繋ぐ」は
/// **N-1（画像経路を一本化するか）待ち**である。
/// → ★この層が持つのは「振り分け」までで、置き場は呼び出し側が決める。
///
/// ★★ 渡さなければ今までどおりである ★★
/// [MasterImporter] は保存先が無ければ画像を **未対応** として扱う
/// （ハッシュだけ記録して結果に載せる / 決定 D39 と同じ形）。
/// ★「置き場が決まっていないから取り込み全体が止まる」形にしない。
library;

/// 配信物の `images/...` を受け取る先。
abstract interface class MasterImageSink {
  /// 1 件保存する。[path] は配信物のマニフェスト上の path。
  ///
  /// ★[bytes] は配るバイト列そのものである (決定 D121-2 の柵)。
  ///   ★文字列に畳まないこと —— WebP は UTF-8 として復号できない。
  Future<void> write(String path, List<int> bytes);

  /// 1 件消す。
  ///
  /// ★配信側から消えた画像に対して呼ばれる。
  ///   ★★無ければ黙って戻ること★★ —— 消す計画は
  ///   「取り込み済みとして記録されている」ことだけを根拠にしており、
  ///   実体が既に無い場合がある。
  Future<void> delete(String path);
}
