/// デッキの**衝突判定** —— 候補 L（決定 **D111-2**）.
///
/// ★★ 候補 L は「操作の★有無 ＋ 内容ハッシュ」である ★★
/// G（操作の有無）で拾ったうえで、★**内容が基準と一致するものを落とす**
/// （`docs/同期設計メモ.md` §18-2-4 の L の行 / §19-3 の「空振りの中身」）。
/// ★G の空振りは「保存を挟んで変えて戻す」場合である —— ★操作は 2 件ログに残るが、
/// ★**内容は基準に戻っている。**★L はここを落とす。
///
/// ★★ この版は「判定」だけである。★解決も送信も無い ★★
/// ★**解決（コミット 14）は入っていない** —— ★`updatedAt` が同値のときの決め方が
/// `lib` にも `docs` にも 1 つも無く、★**解くには (f-6) を開くことである**（**D115-8**）。
/// ★**開き直さない。**
/// ★**送信（コミット 23）も入っていない** —— ★門 エ の下流である。
///
/// ★★ 誰が呼ぶか ★★
/// ★**送信側のアプリである**（**D121-4** ＝ 主-1「衝突を解くのは送信側」）。
/// ★**サーバーは呼ばない** —— ★線 α の許可リストは空で始まる（**D115-6**）。
/// ★**`loveca_db` も呼ばない** —— ★DB はハッシュを文字列として持つだけである（§25-4）。
///
/// ★★ 総合ルールの条番号は 1 つも引かない ★★
/// これはゲームの規則ではなく**同期の判定**である（`deck_edit_op.dart` と同じ扱い）。
library;

/// 前回同期時点に器（**D114-1**）が持っている量。
///
/// ★★ 2 つを 1 つの record にしてあるのは、★器がそう決まっているからである ★★
/// **D114-1** は「★目印と基準ハッシュを★**同じ行**に持つ」と決め、
/// **D114-4** の 1 が「★**片方だけ在る状態を作れない**」ことを利得として挙げている。
/// → ★**型でも片方だけ渡せないようにする。**★規約ではなく形で守る。
///
/// ★★ [hasOpsSinceMark] は目印そのものではない ★★
/// ★目印は `deck_edit_ops` の位置である（**D114-2**）。★ここに要るのは
/// 「★その位置より後ろに操作が 1 件以上在るか」という**答え**だけで、
/// ★**位置そのものは要らない**（G が見るのは有無である / §18-2-4）。
/// → ★**引く側（DB）に位置の意味を持たせたまま、判定は純粋にできる。**
///
/// ★★ 目印の値の意味（「最後に送った」か「次に送る」か）はここで決めない ★★
/// **§24-8** が未決にしている。★**有無に畳んでから渡すので、この型には効かない。**
typedef DeckSyncBaseline = ({
  /// ★目印より後ろに編集ログが 1 件以上在るか（★候補 G の見る量）。
  bool hasOpsSinceMark,

  /// ★前回同期時点の内容ハッシュ（`deckContentHash` の形）。
  String contentHash,
});

/// 判定の結果。★**送るか / 解くかは決めない。**
enum DeckConflictVerdict {
  /// ★★ 器の行が無い ＝ まだ一度も同期していない（決定 **D114-3**）★★
  ///
  /// ★**この関数は「何をするか」を答えない。**★基準が無いので変化を測れない。
  /// ★初回同期の設計（★門 カ）と、★**N-17** / **N-19** の (3) の「そのあと」が決める
  /// （**D119-5** / **D121-7** が同じ断りを付けている）。
  ///
  /// ★★ この枝が要る理由（★**事実 16**）★★
  /// `create` / `duplicate` は編集ログを 1 件も残さない。
  /// → ★**有無だけで判定すると新規デッキが一度も送られない**（§18-2-4 の G の (乙)）。
  /// ★**目印の不在で吸収する**と **D114-3** が決めた分がこれである。
  neverSynced,

  /// ★どちら側も基準から変わっていない。
  unchanged,

  /// ★自分側だけが変わった。
  localOnly,

  /// ★相手側だけが変わった。
  remoteOnly,

  /// ★★ 両側が変わった ＝ (f-1) の言う衝突である ★★
  /// ★解決は **(f-2)** の粒-1（デッキ 1 つを丸ごと / **D112-1**）と
  /// 決着層（**D108-2**）が決める。★**この関数はそこへ進まない。**
  conflict,
}

/// 判定の答え。
///
/// ★★ record にしてあるのは、★フィールドを足した瞬間に全構築点を落とすためである ★★
/// `DeckEditOpRecord`（`deck_edit_op.dart`）と同じ手である。
typedef DeckConflictJudgement = ({
  DeckConflictVerdict verdict,

  /// ★★ 候補 L が「落とした」か —— ★操作は在るが内容が基準と一致する ★★
  ///
  /// ★★ この 1 ビットを捨てないこと ★★
  /// ★捨てると「★操作が 1 件も無い」と「★L が落とした」が**区別できなくなる。**
  /// ★★**論理削除だけが起きたデッキは必ずここに入る**★★ ——
  /// `deletedAt` は内容ハッシュの 5 フィールドに入っていない（**D111-4**）ので、
  /// ★**削除しても内容ハッシュは 1 ビットも変わらない**（**D116-12**：
  /// 「★削除を見る手段はログ 1 つだけである」）。
  ///
  /// ★★ どう扱うかはここで決めない ★★
  /// ★**候補 L の定義は「内容が一致するものを落とす」までである**（§18-2-4）。
  /// ★**そこに削除の例外を足すことは (f-1) を開き直すことである。★していない。**
  /// → ★**事実だけを外へ出す。**★送信の側（コミット 23）が、ログの `kind` を見るなり
  ///   別の量を足すなりを**決めてから**扱う。
  bool droppedLocalOpsByContent,
});

/// 候補 L の判定（決定 **D111-2**）。★**純粋関数である。**
///
/// | 引数 | 何か |
/// |---|---|
/// | [baseline] | ★器の行（**D114-1**）。★**行が無ければ `null`**（**D114-3**） |
/// | [localContentHash] | ★いまの自分側の内容ハッシュ |
/// | [remoteContentHash] | ★受け取った相手側の内容ハッシュ |
///
/// ★★ 相手側は操作の有無を見ない（★見られない）★★
/// §18-2-4 の G は「目印が★両側ぶん要る」と書いたが、★**§18-2-3 の「もう半分」は
/// (c) —— 相手の内容を受け取って比べる —— に決まった**（**D124-7**）。
/// → ★**器に相手側の列は 1 つも無い。**★相手側は内容ハッシュだけで判定する。
///
/// ★★ 相手がそのデッキを持たない場合はこの関数の外である ★★
/// ★送信の流れ（コミット 21 / 23）と初回同期の設計（★門 カ）が決める。
/// ★**ここで `null` を受けて答えを作らない。**★決めたことになる。
///
/// ★★ 両側が同じ内容へ変わった場合は [DeckConflictVerdict.conflict] である ★★
/// ★**候補 L はそこを落とさない**（★落とすのは「基準と一致するもの」であって
/// 「両側が一致するもの」ではない / §18-2-4 / §19-3）。
/// ★**解決は空振りになるが、★害は無い**（粒-1 はどちらを採っても同じ内容になる）。
/// ★**特別扱いを足すことは L の定義を変えることである。★していない。**
DeckConflictJudgement judgeDeckConflict({
  required DeckSyncBaseline? baseline,
  required String localContentHash,
  required String remoteContentHash,
}) {
  if (baseline == null) {
    // ★行の不在は「まだ一度も同期していない」である（**D114-3**）。
    //   ★「消えた」とも読めるので、★意味づけは別に決めてある。
    return (
      verdict: DeckConflictVerdict.neverSynced,
      droppedLocalOpsByContent: false,
    );
  }

  // ★★ G の段 —— 目印より後ろに操作が在るか ★★
  // ★★ L の段 —— そのうち内容が基準と一致するものを落とす ★★
  final localContentMoved = localContentHash != baseline.contentHash;
  final localChanged = baseline.hasOpsSinceMark && localContentMoved;
  final dropped = baseline.hasOpsSinceMark && !localContentMoved;

  // ★相手側は内容だけで見る（★上の doc の (c)）。
  final remoteChanged = remoteContentHash != baseline.contentHash;

  final DeckConflictVerdict verdict;
  if (localChanged && remoteChanged) {
    verdict = DeckConflictVerdict.conflict;
  } else if (localChanged) {
    verdict = DeckConflictVerdict.localOnly;
  } else if (remoteChanged) {
    verdict = DeckConflictVerdict.remoteOnly;
  } else {
    verdict = DeckConflictVerdict.unchanged;
  }

  return (verdict: verdict, droppedLocalOpsByContent: dropped);
}
