/// デッキ編集の操作の**語彙**（決定 D110-1）.
///
/// ★★ なぜ `loveca_core` に置くか ★★
/// 決定 **D110-1** は同期の**検出層**に「操作の履歴（編集ログ）」を採った。
/// ログを書くのは `loveca_db`（削除 / **D110-3** の C-iv）と `loveca-ui`（9 操作 / **D110-2**）の
/// **両方**であり、★**語彙が片方に寄ると同じ列挙が 2 箇所に載る。**
/// → **D99** の比較器（`rules/deck_order.dart`）とまったく同じ理由・同じ配置である
///   —— あちらも `loveca-ui` と `loveca_db` の両方から呼ばれる。
///
/// ★★ この版が決めていないこと —— 3 つ。倒さないこと ★★
/// 1. ★**引数（何を持つか）**。`moveEntry` の挿入位置や `sortByRule` の中身は
///    `docs/同期設計メモ.md` §17-9-2 の 2 / 4 が**未決**である。
///    ★**とくに `sortByRule` を「規則の名前」で持つか「結果の並び」で持つかは
///    (f-3) の軸 B に直結する**（規則で持って再生するとマスタ依存になる / §13-5）。
///    → ★**ここでは種類だけを置き、引数の型を 1 つも定義しない。**
/// 2. ★**いつ書くか**（保存の時点か操作のたびか）。同 §17-9-2 の 3。
/// 3. ★★**未知のキーをどう扱うか。**★★ [DeckEditOpKind.tryFromKey] は **null を返すだけ**で、
///    ★**例外を投げるかどうかを決めていない。**
///    ★理由: **D105-5**（サーバーとアプリを同時に更新できる前提にしない）により
///    「新しい版が書いたログを古い版が読む」が起こりうる。★その扱いは **N-12** の下流であり、
///    `HeartColor.fromKey` 系の厳格性の議論（**D-1** / 束 A の A-4）とも重なる。
///    → ★**方針は記録層が決める。★語彙は決めない。**
///
/// ★ 総合ルールの条番号は 1 つも引かない。
///   これはゲームの規則ではなく**同期の語彙**である（`CLAUDE.md` §1 の「根拠のない数値・条件を
///   書かない」に対しては、根拠として決定番号を引いている）。
library;

/// デッキに対する 1 回の編集操作の**種類**。
///
/// ★★ 9 つは `DeckEditStore` の名前つきの操作、10 個目は削除である ★★
/// 前者は **D110-2**（穴 (a) / 記録点は `DeckEditStore`）、
/// 後者は **D110-3**（穴 (c) / 記録点は `DeckDao.softDelete`）が定めた記録点に対応する。
/// ★**削除だけ形が違う** —— ドラフトを作らずその場で DB へ行く（`docs/同期設計メモ.md` §15-7-6 の (1)）。
/// → ★**「9 操作の 10 個目」ではない。★同じ列挙に入れるのは「ログに 1 件残す」点が同じだからである。**
enum DeckEditOpKind {
  /// 名前を変えた。
  setName('setName'),

  /// メモを変えた。
  setMemo('setMemo'),

  /// 中身をまるごと差し替えた（共有形式からの取り込み / 決定 D67）。
  replaceEntries('replaceEntries'),

  /// メタ（名前 / メモ / タグ / カバー）をまとめて変えた。
  applyMeta('applyMeta'),

  /// カードを足した。★挿入位置を伴いうる（決定 D99）。
  addCard('addCard'),

  /// 同じ刷りを 1 枚減らした。
  removeCopy('removeCopy'),

  /// 刷りの行ごと外した。
  removeEntry('removeEntry'),

  /// 並べ替えた（決定 D99 が手動並べ替えを残した。★`ord` に答えを持つのはこの操作である）。
  moveEntry('moveEntry'),

  /// 並びを規則順に戻した（決定 D99）。
  sortByRule('sortByRule'),

  /// 論理削除した（決定 D102 / 記録点は **D110-3** の C-iv）。
  ///
  /// ★★ Dart の識別子とキーがわざと違う ★★
  /// キーは**記録点のメソッド名**（`DeckDao.softDelete`）に揃えてある。
  /// ほかの 9 つも同じ規則（`DeckEditStore` のメソッド名）で付いている。
  /// ★**識別子だけ `deleteDeck` にしたのは、列挙の中で「消す」ことが読み取れるようにするためである。**
  /// → ★**この 1 件が「キーは識別子の写しではない」ことの実物になっている**（下のテストが対で見る）。
  deleteDeck('softDelete');

  const DeckEditOpKind(this.key);

  /// ★★ 永続化と同期に使う安定な字面 ★★
  /// ★**Dart の識別子を使わない。**識別子を変えただけで DB の中身と送信済みのログが
  /// 意味を失う（★リネームは実装の都合であって、語彙の変更ではない）。
  final String key;

  /// [key] から引く。★**知らないキーは `null`。★例外は投げない。**
  ///
  /// ★★ これは「寛容にする」という決定ではない ★★
  /// 上の library doc の 3 —— ★**未知キーの方針は記録層が決める。**
  /// ★`null` を受け取った側が「捨てる / 止める / 保留する」のどれを採るかは、
  /// **N-12**（サーバー ↔ アプリの版のずれ）が決まってからである。
  static DeckEditOpKind? tryFromKey(String key) {
    for (final kind in DeckEditOpKind.values) {
      if (kind.key == key) return kind;
    }
    return null;
  }
}
