/// デッキに対する 1 回の編集操作の**種類**。
///
/// ★★ 9 つは `DeckEditStore` の名前つきの操作、10 個目は削除である ★★
/// 前者は **D110-2**（穴 (a) / 記録点は `DeckEditStore`）、
/// 後者は **D110-3**（穴 (c) / 記録点は `DeckDao.softDelete`）が定めた記録点に対応する。
/// ★**削除だけ形が違う** —— ドラフトを作らずその場で DB へ行く（`docs/同期設計メモ.md` §15-7-6 の (1)）。
/// → ★**「9 操作の 10 個目」ではない。★同じ列挙に入れるのは「ログに 1 件残す」点が同じだからである。**
enum DeckEditOpKind {
  /// 名前を変えた。
  setName('setName'),

  /// メモを変えた。
  setMemo('setMemo'),

  /// 中身をまるごと差し替えた（共有形式からの取り込み / 決定 D67）。
  replaceEntries('replaceEntries'),

  /// メタ（名前 / メモ / タグ / カバー）をまとめて変えた。
  applyMeta('applyMeta'),

  /// カードを足した。★挿入位置を伴いうる（決定 D99）。
  addCard('addCard'),

  /// 同じ刷りを 1 枚減らした。
  removeCopy('removeCopy'),

  /// 刷りの行ごと外した。
  removeEntry('removeEntry'),

  /// 並べ替えた（決定 D99 が手動並べ替えを残した。★`ord` に答えを持つのはこの操作である）。
  moveEntry('moveEntry'),

  /// 並びを規則順に戻した（決定 D99）。
  sortByRule('sortByRule'),

  /// 論理削除した（決定 D102 / 記録点は **D110-3** の C-iv）。
  ///
  /// ★★ Dart の識別子とキーがわざと違う ★★
  /// キーは**記録点のメソッド名**（`DeckDao.softDelete`）に揃えてある。
  /// ほかの 9 つも同じ規則（`DeckEditStore` のメソッド名）で付いている。
  /// ★**識別子だけ `deleteDeck` にしたのは、列挙の中で「消す」ことが読み取れるようにするためである。**
  /// → ★**この 1 件が「キーは識別子の写しではない」ことの実物になっている**（下のテストが対で見る）。
  deleteDeck('softDelete');

  const DeckEditOpKind(this.key);

  /// ★★ 永続化と同期に使う安定な字面 ★★
  /// ★**Dart の識別子を使わない。**識別子を変えただけで DB の中身と送信済みのログが
  /// 意味を失う（★リネームは実装の都合であって、語彙の変更ではない）。
  final String key;

  /// [key] から引く。★**知らないキーは `null`。★例外は投げない。**
  ///
  /// ★★ これは「寛容にする」という決定ではない ★★
  /// 上の library doc の 3 —— ★**未知キーの方針は記録層が決める。**
  /// ★`null` を受け取った側が「捨てる / 止める / 保留する」のどれを採るかは、
  /// **N-12**（サーバー ↔ アプリの版のずれ）が決まってからである。
  static DeckEditOpKind? tryFromKey(String key) {
    for (final kind in DeckEditOpKind.values) {
      if (kind.key == key) return kind;
    }
    return null;
  }
}

