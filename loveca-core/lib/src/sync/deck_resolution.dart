library;

import '../entities/deck.dart';
import 'deck_content_hash.dart';

/// どちら側が勝ったか。
///
/// ★★ 「自分 / 相手」ではなく「手元 / 受け取った版」と呼ぶ ★★
/// ★**段 2 は対称である**（★上の doc）。★**呼び名だけが★呼ぶ側から見た向きを持つ。**
enum DeckResolutionWinner {
  /// ★手元の版が勝った。
  local,

  /// ★受け取った版が勝った。
  remote,
}

/// なぜその側が勝ったか。
///
/// ★★ 段を外へ出す ★★
/// ★**「どちらが勝ったか」だけでは、★★段 2 を通ったかが分からない★★。**
/// ★**段 2 は★★秒が同じときにしか働かない★★**ので、★通ったこと自体が観測に値する
/// （★**D115-8** の測定 1 —— ★★保存精度は秒である★★）。
enum DeckResolutionReason {
  /// ★段 1 —— ★`updatedAt` が新しいほうが勝った（**D108-2**）。
  updatedAt,

  /// ★★段 2 —— ★`updatedAt` が同値で、★内容ハッシュの字面で決めた（**D138-1**）★★。
  contentHashTieBreak,

  /// ★★内容が同じだった ＝ ★どちらを採っても同じである★★。
  ///
  /// ★**候補 L は「両側が同じ内容へ変わった場合」も衝突のままにする**（**D111-2** / `deck_conflict.dart`）。
  /// → ★**解決は空振りになるが害は無い**（★あちらの doc がそう書いている）。
  /// ★**その空振りを★★呼ぶ側から見えるようにする★★**（★畳むと「解決した」と区別がつかない）。
  identical,
}

/// 解決の答え。
///
/// ★★ record にしてあるのは、★フィールドを足した瞬間に全構築点を落とすためである ★★
/// `DeckConflictJudgement` / `DeckEditOpRecord` と同じ手である。
typedef DeckResolution = ({
  /// ★勝った側の `Deck`（★★入力の片方そのもの★★ / **D112-1** ＝ 粒-1）。
  Deck winner,

  /// ★どちらが勝ったか。
  DeckResolutionWinner side,

  /// ★どの段で決まったか。
  DeckResolutionReason reason,
});

/// 衝突を解く（決定 **D108-2** ＋ **D138-1**）。★**純粋関数である。**
///
/// | 引数 | 何か |
/// |---|---|
/// | [local] | ★手元の版（★★DB から読んだもの★★ / **D138-4** の柵） |
/// | [remote] | ★受け取った版 |
///
/// ★★ 判定を呼ばない。★呼ぶ側が判定してから渡す ★★
/// ★**`judgeDeckConflict` が `conflict` を返した場合にだけ意味を持つ**が、
/// ★**それを★この関数が確かめることはできない**（★器も目印も引数に無い）。
/// → ★**2 つを 1 つにしない。★段が違う**（★§32-6 も 13 と 14 を別のコミットにしている）。
///
/// ★★ 削除（`deletedAt`）を特別扱いしない ★★
/// ★**内容ハッシュの 5 フィールドに `deletedAt` は入らない**（**D111-4**）が、
/// ★**ここが見るのは `updatedAt` と★内容ハッシュだけである。**
/// ★**削除の扱いを足すことは (f-2) の 粒-1 を開き直すことである。★していない**（**D112-1**）。
DeckResolution resolveDeckConflict({
  required Deck local,
  required Deck remote,
}) {
  // ★★ 段 1 —— `updatedAt` の新しいほう（**D108-2**）★★
  final compared = local.updatedAt.compareTo(remote.updatedAt);
  if (compared > 0) {
    return (
      winner: local,
      side: DeckResolutionWinner.local,
      reason: DeckResolutionReason.updatedAt,
    );
  }
  if (compared < 0) {
    return (
      winner: remote,
      side: DeckResolutionWinner.remote,
      reason: DeckResolutionReason.updatedAt,
    );
  }

  // ★★ 段 2 —— 同値。★内容ハッシュの字面で決める（**D138-1**）★★
  //   ★**対称でなければならない**（★「自分」を勝たせると収束しない / §65-5）。
  final localHash = deckContentHash(local);
  final remoteHash = deckContentHash(remote);
  final byHash = localHash.compareTo(remoteHash);
  if (byHash == 0) {
    // ★★ 内容が同じ ＝ どちらを採っても同じである ★★
    //   ★手元を返すのは★★呼ぶ側の書き込みを減らすためであって、★決着ではない★★。
    return (
      winner: local,
      side: DeckResolutionWinner.local,
      reason: DeckResolutionReason.identical,
    );
  }

  // ★★ 向きは好みである（**D138-2**）。★差し替え点はこの 1 行だけである ★★
  final localWins = byHash > 0;
  return (
    winner: localWins ? local : remote,
    side: localWins ? DeckResolutionWinner.local : DeckResolutionWinner.remote,
    reason: DeckResolutionReason.contentHashTieBreak,
  );
}
