/// ★★ 2026-09-02 追記: ★★段 3 として★削除の状態を見るようになった（**D147-1**）★★
/// ★★**上の 4 行は 1 文字も書き換えない**★★（**D-35** —— ★★その時点では真である★★）。
/// ★**変わったのは★★`updatedAt` も内容ハッシュも同値だったときだけである★★。**
/// ★★**(f-2) の 粒-1 は 1 ミリも動かない**★★ —— ★**マージしていない。★★勝った側の `Deck` を丸ごと返す★★。**
/// ★**引き金は★★収束しなかったこと★★である**（★上の doc / ★待ち行列の **W-43**）。
DeckResolution resolveDeckConflict({
  required Deck local,
  required Deck remote,
}) {
  // ★★ 段 1 —— `updatedAt` の新しいほう（**D108-2**）★★
  final compared = local.updatedAt.compareTo(remote.updatedAt);
  if (compared > 0) {
    return (
      winner: local,
      side: DeckResolutionWinner.local,
      reason: DeckResolutionReason.updatedAt,
    );
  }
  if (compared < 0) {
    return (
      winner: remote,
      side: DeckResolutionWinner.remote,
      reason: DeckResolutionReason.updatedAt,
    );
  }

  // ★★ 段 2 —— 同値。★内容ハッシュの字面で決める（**D138-1**）★★
  //   ★**対称でなければならない**（★「自分」を勝たせると収束しない / §65-5）。
  final localHash = deckContentHash(local);
  final remoteHash = deckContentHash(remote);
  final byHash = localHash.compareTo(remoteHash);
  if (byHash != 0) {
    // ★★ 向きは好みである（**D138-2**）。★差し替え点はこの 1 行だけである ★★
    final localWins = byHash > 0;
    return (
      winner: localWins ? local : remote,
      side:
          localWins ? DeckResolutionWinner.local : DeckResolutionWinner.remote,
      reason: DeckResolutionReason.contentHashTieBreak,
    );
  }

  // ★★ 段 3 —— 時刻も内容も同値。★削除の状態で決める（**D147-1**）★★
  //   ★**段 2 が決めた場合はここへ来ない**（★**D138-1** の答えを 1 ミリも変えない）。
  //   ★**対称でなければならない**（★段 2 とまったく同じ理由 / §65-5 の 同-1）。
  final byDeletion = compareDeckDeletion(local.deletedAt, remote.deletedAt);
  if (byDeletion != 0) {
    final localWins = byDeletion > 0;
    return (
      winner: localWins ? local : remote,
      side:
          localWins ? DeckResolutionWinner.local : DeckResolutionWinner.remote,
      reason: DeckResolutionReason.deletionTieBreak,
    );
  }

  // ★★ 3 つとも同値 ＝ どちらを採っても同じである ★★
  //   ★手元を返すのは★★呼ぶ側の書き込みを減らすためであって、★決着ではない★★。
  return (
    winner: local,
    side: DeckResolutionWinner.local,
    reason: DeckResolutionReason.identical,
  );
}

/// 段 3 の比較（**D147-1** / **D147-2**）。★**純粋関数である。**
///
/// ★★ 返す値 ★★
/// ★**正なら [a] の側が勝ち、★負なら [b] の側が勝ち、★0 なら決まらない。**
