/// ★★ 生きているほうが勝つ（**D147-2**）★★
/// ★**決め手は★★誤ったときに★利用者が手で戻せるかである★★** ——
/// ★**削除が勝つ形では★生きていた側のデッキが消え、★★復元の口を置かないと決めている★★**（**D117-4**）。
/// ★**生存が勝つ形なら★★もう一度消せばよい★★**（★2 度目は `updatedAt` が新しいので段 1 で決まる）。
/// ★★**「削除が勝つ」が劣るとは書かない**★★ —— ★**D117-4 を開き直せば★★到達する★★。**
///
/// ★★ 両方が削除されているときは★`deletedAt` の新しいほう。★好みである ★★
/// ★**見た目はどちらでも同じである**（★どちらも消えている）。★**根拠は無い**（**D138-2** と同じ格）。
/// ★★**畳んで 0 を返してはならない**★★ —— ★**それは `identical` へ落ちて★★また 同-1 になる★★
/// （★2 台が★自分の `deletedAt` を押し合って★永久に食い違う）。
///
/// ★★ 対称である ★★
/// ★**`compareDeckDeletion(x, y) == -compareDeckDeletion(y, x)` である**（★対で固定した）。
int compareDeckDeletion(DateTime? a, DateTime? b) {
  if (a == null && b == null) return 0;
  // ★★ 生きている（null）ほうが勝つ ★★
  if (a == null) return 1;
  if (b == null) return -1;
  // ★★ 両方削除 —— ★新しいほう（★全順序であることだけが要る）★★
  return a.compareTo(b);
}
