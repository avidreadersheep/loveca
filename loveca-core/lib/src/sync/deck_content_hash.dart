/// デッキの**内容ハッシュ**（**N-18** / 決定 **D115-1** / **D115-2**）.
///
/// ★★ 入力は `deck_content.dart` が固定した表現である ★★
/// **D115-3** が「★入力の正規化された表現を★固定してからでないと 2 台が交換できない」と
/// 定めており、★**その順序どおりに、固定した表現の上にだけ畳む関数を置く。**
/// ★ここで `Deck` から直に組み立て直さないこと —— ★**表現が 2 か所になった時点で
/// 「2 台が同じ値を出す」保証が消える。**
///
/// ★★ デッキ 1 つにつき 1 個である（決定 **D115-1**）★★
/// ★5 個に分けることは **(f-1)** を開き直すことである（**D112** の **N-18** 追記）。
/// ★器（**D114-1**）の行もデッキ 1 つにつき 1 つで、★ハッシュの列は 1 本である。
///
/// ★★ SHA-256 である（決定 **D115-2**）★★
/// ★決め手は「★要求が仕様の側に在る」こと —— ★**版と端末をまたいで安定**であることを
/// 規格が持っており、★**こちらが保証するものが無い。**
/// ★自前の畳み込み（畳-2）は到達するが、★安定であることと幅を★自分で保証することになり、
/// ★**破れたときの壊れ方が「全デッキが衝突」で、★壊れたことが値からは見えない**
/// （`docs/同期設計メモ.md` §25-4）。★**比べて採らなかったのであって、劣るのではない。**
library;

import 'package:crypto/crypto.dart';

import '../entities/deck.dart';
import 'deck_content.dart';

/// ハッシュの字面の接頭辞。★**どの関数で畳んだかを値そのものが名乗る。**
///
/// ★配信物の `manifest.json` / `version.json` と同じ形にしてある
/// （`master_files.hash` の doc / `build_dist.py`）。★**同じ層の同じ形をなぞる。**
/// ★これが無いと、★畳み方を変えたときに**古い値と新しい値が字面で見分けられない。**
const String deckContentHashPrefix = 'sha256:';

/// [deck] の内容ハッシュ。★`"sha256:<小文字 16 進>"`。
///
/// ★★ 掴む対象は 5 フィールドである（決定 **D111-4**）★★
/// ★[canonicalDeckContentBytes] がそれを固定している。
/// ★**`Deck.toJson()` を素直に使うと L が G に退化する** —— `updatedAt` / `revision` が
/// 保存のたびに動くので、候補 L（**D111-2**）の「内容が一致するものを落とす」段が
/// 1 度も働かなくなる。
///
/// ★★ この値が「変わらない」ことの意味 ★★
/// ★**論理削除は 1 ビットも現れない**（**D116-12** —— `deletedAt` は 5 フィールドに無い）。
/// ★削除を見る手段はログ 1 つだけである。★読む側が知っていなければならない。
///
/// ★★ 衝突したときに何が起きるか（★隠さない）★★
/// ★**本物の変更を落とす** —— 候補 L の「落とす」段がそのまま誤爆する
/// （`docs/同期設計メモ.md` §25-4 の (甲)）。★SHA-256 では事実上起きない。
String deckContentHash(Deck deck) =>
    '$deckContentHashPrefix${sha256.convert(canonicalDeckContentBytes(deck))}';
