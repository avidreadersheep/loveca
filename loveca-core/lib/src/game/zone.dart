/// 領域の型.
///
/// 総合ルール 4 章に対応。Phase 3a の入力は `docs/PhaseEngine設計メモ.md`。
///
/// ★★ 総合ルール 4 章が定義する領域は 11 種ちょうど ★★
///   4.4〜4.14 が 1 節 1 領域で並んでおり、増減の余地は無い。
///   ルールに存在しない置き場 (6.2.1.6 の脇置き / UI 都合のフリーエリア) は
///   [OutOfRuleZone] として別の型に分ける。同じ enum に混ぜてはいけない。

library;

/// 領域の可視状態。総合ルール 4.1.2。
///
/// - [public]  … 4.1.2「すべてのプレイヤーがカードの内容を見ることができる領域」
/// - [private] … 4.1.2「特定のプレイヤーが内容を見ることができない領域」
///
/// 4.1.2.2 により、公開・非公開にかかわらず**枚数はいつでも全プレイヤーが確認できる**。
enum ZoneVisibility { public, private }

/// 総合ルール 4 章が定義する領域。★この 11 種以外を足さない★
///
/// ルール外の置き場を混ぜると、
/// 4.1.7 (メンバーエリアやライブカード置き場以外へ移動する場合はオーナーの領域へ) や
/// 4.1.4 (領域間の移動では新しいカードとみなす) を、
/// 条文が想定していない置き場にも適用してしまう。
enum Zone {
  /// 総合ルール 4.4 ステージ。
  ///
  /// ★カードを直接置く領域ではない。
  ///   4.4.1「プレイヤーのメンバーエリアを統合した領域です」であり、
  ///   4.4.2 によりプレイヤーはステージ内に自身のメンバーエリア (4.5) を持つ。
  ///   実体は [memberArea] 側にあり、ステージはその統合ビュー。
  ///
  ///   それでも領域として持つのは、条文が「ステージ」を直接参照するため。
  ///   例: 9.6.2.1.2.1 の登場制限「そのターンにステージ外からステージに来たメンバー」。
  ///
  ///   4.4 は可視状態も順番管理も規定していないため [visibility] / [isOrdered] は null。
  stage('4.4', null, null),

  /// 総合ルール 4.5 メンバーエリア。プレイしたメンバーカードを置く (4.5.1)。
  ///
  /// 4.5.3: すべてのプレイヤーに対して公開領域で、カードの順番は管理されない。
  /// 4.5.2.1 により左サイド / センター / 右サイドの 3 つ ([MemberAreaSlot])。
  memberArea('4.5', ZoneVisibility.public, false),

  /// 総合ルール 4.6 ライブカード置き場。
  ///
  /// 4.6.2: 公開領域だが**カードが一時的に裏向きに置かれることがある**。
  /// 8.2.2 / 8.2.4 で裏向きに置き、8.3.4 で表向きにする。順番は管理されない。
  liveStage('4.6', ZoneVisibility.public, false),

  /// 総合ルール 4.7 エネルギー置き場。
  ///
  /// 4.7.2: 公開領域で順番は管理されない。
  /// 4.7.3: この領域のカードは向きを示す配置状態を持つ。
  /// ★5.9.1 のコスト支払いはウェイトにするだけで、カードはこの領域から動かない。
  energyField('4.7', ZoneVisibility.public, false),

  /// 総合ルール 4.8 メインデッキ置き場。
  ///
  /// 4.8.2: ★**非公開領域で、カードの順番が管理される**。
  /// 10.2.3 のリフレッシュは控え室をシャッフルしてこの領域の**下**へ差し込む。
  mainDeck('4.8', ZoneVisibility.private, true),

  /// 総合ルール 4.9 エネルギーデッキ置き場。
  ///
  /// 4.9.2: 非公開領域で、★**カードの順番は管理されない**。
  ///
  /// ★★ 6.2.1.7「上から 3 枚」/ 7.5.2「一番上のカード」との不整合（B-2）は
  ///   **決定 D73 で解消した。無作為 1 枚抽出を採る**（4.9.3 が決め手）★★
  ///
  ///   ここには「非公開領域なので観測上の差は出ない」と書いてあったが、**誤り**。
  ///   6.2.1.3 がシャッフルを指示しないので、この領域の並びは
  ///   **デッキリストを並べた順そのもの**になる。「一番上」を採ると
  ///   4.9.2 が奪っているはずの選択をプレイヤーに返してしまう。
  ///   根拠と 3 案の対比は `energy_deck.dart` / `docs/盤面設計メモ.md` §2。
  energyDeck('4.9', ZoneVisibility.private, false),

  /// 総合ルール 4.10 成功ライブカード置き場。
  ///
  /// 4.10.2: 公開領域で★**順番が管理され、これまでに置かれているカードの上に置く**。
  /// 1.2.1.1 の勝利条件 (3 枚) が数える領域。
  /// ★10.3.1 は「勝利ライブカード置き場」と書くが誤記。1.2.1.1 / 4.10 が正 (設計メモ §10)。
  successLive('4.10', ZoneVisibility.public, true),

  /// 総合ルール 4.11 手札。
  ///
  /// 4.11.2: 非公開領域。自分の手札は自分のみが自由に確認できる。順番は管理されない。
  hand('4.11', ZoneVisibility.private, false),

  /// 総合ルール 4.12 控え室。
  ///
  /// 4.12.2: 公開領域で順番は管理されない。
  /// ★ルール処理でエネルギーカードがここへ来る経路は存在しない (10.5.5 を広義に読む / 設計メモ §9)。
  waitingRoom('4.12', ZoneVisibility.public, false),

  /// 総合ルール 4.13 除外領域。
  ///
  /// 4.13.2: 原則として公開領域。この領域のカードは表示面の状態を持ち、
  /// 特に指示がないかぎり表向きに置かれる。順番は管理されない。
  exile('4.13', ZoneVisibility.public, false),

  /// 総合ルール 4.14 解決領域。
  ///
  /// ★★ 4.14.1: 両プレイヤーが共有して使用する領域が**1 つだけ**存在する ★★
  ///   他の 10 種と違い、プレイヤーごとに 1 つずつではない ([isShared])。
  ///
  ///   先攻パフォーマンス後も先攻のエールカードが残ったまま後攻パフォーマンスに入るため、
  ///   8.3.14 のハート合計は `ownerId` での絞り込みが必須。
  ///   マスターの定義 (3.1.2「その領域が属しているプレイヤー」) が共有領域では定まらない。
  ///
  /// 4.14.2: 公開領域で順番は管理されない。
  resolution('4.14', ZoneVisibility.public, false, isShared: true);

  const Zone(
    this.ruleRef,
    this.visibility,
    this.isOrdered, {
    this.isShared = false,
  });

  /// この領域を定義する条番号 (4.4〜4.14)。
  final String ruleRef;

  /// 総合ルール 4.1.2 の公開 / 非公開。
  /// null は条文が規定していないことを表す ([Zone.stage] のみ)。
  final ZoneVisibility? visibility;

  /// 総合ルール 4.1.3 の順番管理。
  /// null は条文が規定していないことを表す ([Zone.stage] のみ)。
  final bool? isOrdered;

  /// ★両プレイヤーで共有され、ゲーム中に 1 つだけ存在するか。
  ///
  /// true になるのは [Zone.resolution] のみ (4.14.1)。
  /// 他の領域は 4.1.1 により各プレイヤーがそれぞれ持つ。
  final bool isShared;
}

/// ★総合ルール 4 章の領域では**ない**置き場。
///
/// ★★ [Zone] と同じ enum に混ぜてはいけない ★★
///   混ぜると「4 章の領域は 11 種」という不変条件が崩れ、
///   4.1.7 (オーナーの領域へ移動する) や
///   4.1.4 (領域間の移動では新しいカードとみなす) といった
///   領域に対する規定を、条文が想定していない置き場にも適用してしまう。
///
///   両者に共通の親型を導入しないこと。移動を扱う関数は [Zone] を受け、
///   ルール外の置き場への出し入れは [OutOfRuleZone] を受ける別の関数に分ける。
///   `test/game_types_test.dart` がこの分離を固定している。
enum OutOfRuleZone {
  /// 総合ルール 6.2.1.6 のマリガンで「裏向きに脇に置く」カードの一時置き場。
  ///
  /// ★条文はこれに 4 章の領域名を与えていない。
  ///   6.2.1.6「先攻プレイヤーから順に、各プレイヤーは自身の手札のカードを任意の枚数選んで
  ///   裏向きに脇に置き、置いた枚数と同じ枚数のカードを自身のメインデッキ置き場の上から
  ///   自身の手札に移動し、脇に置いたカードをメインデッキ置き場に移動し、
  ///   1 枚以上移動した場合はシャッフルします」
  ///
  ///   すなわちこの置き場は 6.2.1.6 の手順内にのみ存在し、置いたカードは同じ手順の中で
  ///   メインデッキ置き場へ戻る。枚数上限は無い (「任意の枚数」)。
  mulliganAside,

  /// 盤外の自由置き場。ルールにはまったく存在しない。
  ///
  /// アプリは「盤面・カード・山札・手札をデジタル上で操作するサンドボックス」であり
  /// カード効果の自動処理を行わない (CLAUDE.md §1)。
  /// 効果を手動で処理する際の一時退避先としてこの置き場を使う。
  freeArea,
}

/// メンバーエリアの位置。総合ルール 4.5.2.1。
///
/// 4.5.2.2 により、同一プレイヤーに属する左サイドはセンターの左、センターは右サイドの左。
enum MemberAreaSlot {
  leftSide('左サイドエリア'),
  center('センターエリア'),
  rightSide('右サイドエリア');

  const MemberAreaSlot(this.label);

  /// 総合ルール 4.5.2.1 が定める固有の領域名称。
  final String label;

  /// 他プレイヤーが持つ正面のエリア。総合ルール 4.5.7 / 4.5.7.1。
  ///
  /// ★左サイドの正面は他プレイヤーの**右**サイド。鏡像配置がルール上も正しい。
  MemberAreaSlot get opposing => switch (this) {
        MemberAreaSlot.leftSide => MemberAreaSlot.rightSide,
        MemberAreaSlot.center => MemberAreaSlot.center,
        MemberAreaSlot.rightSide => MemberAreaSlot.leftSide,
      };
}
