/// メンバーエリアの型.
///
/// 総合ルール 4.5 に対応。確定の根拠は `docs/PhaseEngine設計メモ.md` の B-3。
///
/// ★★ 「メンバーが必ず 1 枚居る」前提の型にしないこと ★★
///   条文は、メンバーが 0 枚のエリアにカードだけが残っている状態と、
///   メンバーが 2 枚以上あるエリアの両方を、正規の中間状態として認めている。
///   詳細は [MemberArea] の doc を参照。

library;

import 'card_instance.dart';
import 'zone.dart';

/// メンバーと、その下に重ねて置かれたカードの束。
///
/// 総合ルール 4.5.5「メンバーエリアのメンバーカードの下に、メンバーカードや
/// エネルギーカードが重ねて置かれる場合があります」(ver 1.06 でメンバーカードも可になった)。
class MemberStack {
  const MemberStack({
    required this.member,
    this.beneath = const [],
  });

  /// 一番上のメンバーカード。
  /// 総合ルール 4.5.4 により、向きを示す配置状態を持つ (`orientation != null`)。
  final CardInstance member;

  /// このメンバーの「下にある」カード。総合ルール 4.5.5.1。
  ///
  /// ★4.5.5.2 により向きを示す配置状態を**持たない** (`orientation == null`)。
  ///   帰結として、
  ///     - 8.3.10 のブレード合計の対象外 (アクティブ状態になりえない)
  ///     - UI に縦向き / 横向きの回転操作を出してはいけない
  ///
  /// ★4.5.5.3: このメンバーが**他のメンバーエリア**へ移動する場合、
  ///   下のカードも重なったまま同時に移動する。束のまま動く。
  final List<CardInstance> beneath;

  MemberStack copyWith({
    CardInstance? member,
    List<CardInstance>? beneath,
  }) =>
      MemberStack(
        member: member ?? this.member,
        beneath: beneath ?? this.beneath,
      );
}

/// 1 つのメンバーエリア。総合ルール 4.5。
///
/// ★★ この型が表現できなければならない 3 つの状態 ★★
///
/// 1. **通常** — [stacks] が 1 個。
///
/// 2. **孤児カードだけが残っている** — [stacks] が空で [orphans] が非空。
///
///    総合ルール 4.5.5.4「メンバーエリアのメンバーがメンバーエリア以外の領域に移動する場合、
///    そのメンバーカードのみが移動します」
///    4.5.5.4.1 / 4.5.5.4.2 はいずれも、下に重ねられていたカードは
///    「**そのままそのメンバーエリアに残り、その後にルール処理により**」移動する、と書く。
///
///    そして 10.1.2「ルール処理は、リフレッシュ (10.2) を除き、
///    **チェックタイミングにおいてのみ**条件を満たしているかを確認し、実行されます」
///
///    → 上のメンバーが去ってから次のチェックタイミングまでの間、
///      「上にメンバーが居ないカードがメンバーエリアに存在する」状態が**正規に存在する**。
///      メンバーの移動と同時に下のカードを消す実装は条文違反であり、
///      その間に発生する誘発や参照の結果が変わる。
///
/// 3. **メンバーが 2 枚以上ある** — [stacks] が 2 個以上。
///
///    10.4 の重複メンバー処理待ち。これも 10.1.2 により次のチェックタイミングまで存在する。
///
/// したがって [stacks] を `MemberStack?` にしてはいけない。
class MemberArea {
  const MemberArea({
    required this.slot,
    this.stacks = const [],
    this.orphans = const [],
  });

  /// このエリアの位置。総合ルール 4.5.2.1。
  final MemberAreaSlot slot;

  /// このエリアにあるメンバーとその下のカード。
  ///
  /// ★0 個も 2 個以上もありうる。上の doc の状態 2・3 を参照。
  final List<MemberStack> stacks;

  /// ★上にメンバーが居なくなったカード。総合ルール 4.5.5.4.1 / 4.5.5.4.2。
  ///
  /// 次のチェックタイミングでルール処理により、種別ごとに別々の行き先へ移動する。
  ///
  /// | 取り残されたカード | 行き先 | 条番号 |
  /// |---|---|---|
  /// | メンバーカード | 控え室 | 4.5.5.4.1 → 10.5.3 |
  /// | エネルギーカード | エネルギーデッキ置き場 | 4.5.5.4.2 → 10.5.4 |
  ///
  /// 行き先はいずれもオーナーの領域 (4.1.7)。
  /// ★エネルギーカードは控え室を経由しない閉ループである (10.5.5 を広義に読む)。
  ///   根拠は `docs/PhaseEngine設計メモ.md` §9。
  ///
  /// 束ではなくフラットなリストで持つのは、行き先が種別ごとに分かれるため。
  /// どのメンバーの下にあったかは、解消後の挙動に影響しない。
  final List<CardInstance> orphans;

  /// このエリアにメンバーが 1 枚も居ないか。
  ///
  /// [orphans] だけが残っている状態 (上の doc の状態 2) と、完全に空の状態の
  /// どちらでも true になる。
  bool get hasNoMember => stacks.isEmpty;

  /// 10.4 の重複メンバー処理を待っている状態か。総合ルール 10.4.1。
  bool get hasDuplicateMembers => stacks.length > 1;

  MemberArea copyWith({
    List<MemberStack>? stacks,
    List<CardInstance>? orphans,
  }) =>
      MemberArea(
        slot: slot,
        stacks: stacks ?? this.stacks,
        orphans: orphans ?? this.orphans,
      );
}
